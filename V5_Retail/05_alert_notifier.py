"""DeltaMax V5 Retail alert notifier using SendGrid.

Reads local alerts from results/retail/alerts.csv, writes a local text report,
and emails the alert details through SendGrid when alerts are present.

Required environment variables:
  DELTAMAX_SENDGRID_API_KEY
  DELTAMAX_ALERT_SENDER
  DELTAMAX_ALERT_RECEIVER
"""
import os
import html
from collections import Counter

import pandas as pd
from sendgrid.helpers.mail import Mail
from sendgrid_config import require_sendgrid_config, sendgrid_send

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "results", "retail")
ALERTS_PATH = os.path.join(OUT, "alerts.csv")
REPORT_PATH = os.path.join(OUT, "retail_alert_report.txt")


def _severity_column(df):
    for col in df.columns:
        if col.strip().lower() in {"severity", "risk_level", "alert_level", "risk_category"}:
            return col
    return None


def _build_html(df):
    safe_columns = [str(c) for c in df.columns]
    header = "".join(
        f'<th style="padding:9px;text-align:left;background:#263238;color:#fff;">{html.escape(c)}</th>'
        for c in safe_columns
    )
    body_rows = []
    for _, row in df.iterrows():
        cells = "".join(
            f'<td style="padding:8px;border-bottom:1px solid #ddd;">'
            f'{html.escape(str(value))}</td>'
            for value in row.tolist()
        )
        body_rows.append(f"<tr>{cells}</tr>")
    return f"""<!doctype html><html><body style="font-family:Arial,sans-serif;color:#222;">
    <div style="background:#263238;color:#fff;padding:18px;border-radius:6px;">
      <h2>DeltaMax V5 Retail - Alert Notification</h2>
      <p>Local retail data monitoring results</p>
    </div>
    <p><b>Total alerts:</b> {len(df)}</p>
    <table style="border-collapse:collapse;width:100%;font-size:13px;">
      <thead><tr>{header}</tr></thead><tbody>{''.join(body_rows)}</tbody>
    </table>
    <p style="color:#777;font-size:12px;">Generated by DeltaMax V5 Retail. Data processing and reports remain local.</p>
    </body></html>"""


def _send_email(df):
    _, sender, receiver = require_sendgrid_config(require_receiver=True)

    severity_col = _severity_column(df)
    counts = Counter(df[severity_col].fillna("UNKNOWN").astype(str).str.upper()) if severity_col else Counter()
    if counts:
        summary = " / ".join(f"{name}: {count}" for name, count in counts.most_common(4))
    else:
        summary = f"{len(df)} alert(s)"
    subject = f"DeltaMax V5 Retail Alerts - {summary}"
    message = Mail(
        from_email=sender,
        to_emails=receiver,
        subject=subject,
        html_content=_build_html(df),
    )
    status = sendgrid_send(message)
    print(f"[OK] Alert email accepted by SendGrid (HTTP {status}).")


def main():
    os.makedirs(OUT, exist_ok=True)
    lines = ["DeltaMax V5 Retail Alert Report", ""]

    if not os.path.exists(ALERTS_PATH):
        lines.append("Alert results not found. Run the trust-scoring/alert generation script first.")
        report = "\\n".join(lines) + "\\n"
        with open(REPORT_PATH, "w", encoding="utf-8") as file:
            file.write(report)
        print(report)
        print("No email sent because alerts.csv was not found.")
        print("Saved local report:", REPORT_PATH)
        return

    df = pd.read_csv(ALERTS_PATH)
    lines.append(f"Alerts found: {len(df)}")
    if df.empty:
        lines.append("No alerts found. No email sent.")
    else:
        lines.append(df.to_string(index=False))

    report = "\\n".join(lines) + "\\n"
    with open(REPORT_PATH, "w", encoding="utf-8") as file:
        file.write(report)
    print(report)
    print("Saved local report:", REPORT_PATH)

    if df.empty:
        print("[INFO] No alerts found; no email was sent.")
        return

    _send_email(df)


if __name__ == "__main__":
    main()
