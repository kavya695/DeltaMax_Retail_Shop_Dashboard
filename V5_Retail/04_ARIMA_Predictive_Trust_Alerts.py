"""DeltaMax V5 Retail: display locally saved forecasts and alerts.
Forecasts and alerts are generated by 03_Trust_Score.py as part of the engine pipeline.
"""
import os
import pandas as pd
ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "results", "retail")

def show(name):
    path = os.path.join(OUT, name + ".csv")
    if not os.path.exists(path):
        print(f"{name}: not found. Run python 03_Trust_Score.py first.")
        return
    df = pd.read_csv(path)
    print(f"\\n{name} ({len(df):,} rows) — {path}")
    print(df.head(10).to_string(index=False) if len(df) else "No rows.")
def main():
    show("forecasts")
    show("alerts")
if __name__ == "__main__":
    main()
